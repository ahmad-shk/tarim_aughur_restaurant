type TranslationKeys = keyof typeof translations["en"]

// Type-safe translation getter
export const getTranslation = (
  lang: Language,
  key: TranslationKeys
): string => {
  return translations[lang]?.[key]
    ?? translations.en?.[key]
    ?? "";
};
